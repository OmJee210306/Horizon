import { useEffect } from 'react';
import { X, Lightbulb } from 'lucide-react';
import { Badge } from './ui';
import { parseContributors } from '../format';
import { TIER_COLORS } from '../config';

export default function CustomerDrawer({ customer: c, onClose }) {
  useEffect(() => {
    const h = (e) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', h);
    return () => window.removeEventListener('keydown', h);
  }, [onClose]);
  if (!c) return null;
  const score = Number(c.predicted_churn_probability) * 100;
  const contribs = parseContributors(c.top_model_contributors);
  const max = Math.max(...contribs.map((x) => Math.abs(x.value)), 1);
  return (
    <>
      <div className="overlay" onClick={onClose} />
      <aside className="drawer" role="dialog" aria-label="Customer detail">
        <div className="drawer-head">
          <div>
            <div className="mono" style={{ color: 'var(--faint)' }}>{c.customer_id}</div>
            <h2>{c.company_name}</h2>
            <div style={{ marginTop: 8 }}><Badge tier={c.priority_tier} /></div>
          </div>
          <button className="ibtn" onClick={onClose} aria-label="Close"><X size={16} /></button>
        </div>
        <div className="kv">
          <div><small>Model score</small><b>{score.toFixed(1)}%</b></div>
          <div><small>Risk percentile</small><b>{Number(c.risk_percentile).toFixed(2)}</b></div>
          <div><small>Observed outcome</small><b>{Number(c.actual_is_churned) === 1 ? 'Churned' : 'Retained'}</b></div>
          <div><small>Priority tier</small><b style={{ color: TIER_COLORS[c.priority_tier] }}>{c.priority_tier}</b></div>
        </div>
        <div className="h4">Recommended action</div>
        <div className="callout"><Lightbulb size={15} style={{ verticalAlign: -2, marginRight: 8, color: 'var(--accent)' }} />{c.recommended_action}</div>
        <div className="h4">Model contributors</div>
        {contribs.length === 0 && <p className="sub">Per-customer contribution values are not currently generated by the calibrated batch-scoring pipeline.</p>}
        {contribs.map((x) => (
          <div className="contrib" key={x.name}>
            <span>{x.name}</span>
            <div className="track"><i style={{ width: `${(Math.abs(x.value) / max) * 100}%`, background: x.value >= 0 ? 'var(--bad)' : 'var(--good)' }} /></div>
            <b className="mono">{x.value > 0 ? '+' : ''}{x.value.toFixed(2)}</b>
          </div>
        ))}
        <p style={{ color: 'var(--faint)', fontSize: 12, marginTop: 18 }}>
          Contributions describe model behaviour (red raises the score, green lowers it). They are not causal explanations, and scores are relative rankings rather than calibrated probabilities.
        </p>
      </aside>
    </>
  );
}
